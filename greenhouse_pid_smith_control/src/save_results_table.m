function save_results_table(metrics, scheme_names, save_path)
% save_results_table
% 保存性能指标为 CSV 文件

T = table( ...
    scheme_names, ...
    metrics(:,1), ...
    metrics(:,2), ...
    metrics(:,3), ...
    metrics(:,4), ...
    'VariableNames', { ...
        'Scheme', ...
        'Overshoot_percent', ...
        'RiseTime_s', ...
        'SettlingTime_s', ...
        'IAE' ...
    } ...
);

writetable(T, save_path);
end
